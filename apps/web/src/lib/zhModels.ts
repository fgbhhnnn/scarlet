export function modelOptionLabel(option: { id: string; label?: string }) {
  const label = option.label ?? option.id.charAt(0).toUpperCase() + option.id.slice(1);
  const key = label.toLowerCase();
  return (Object.hasOwn(optionLabels, key) ? optionLabels[key] : undefined) ?? label;
}

export function modelScrollCue(activeBelow: number, hiddenBelow: number, totalHidden: number) {
  if (activeBelow && hiddenBelow) return `下方还有 ${activeBelow + hiddenBelow} 个模型 · ${hiddenBelow} 个已隐藏`;
  if (activeBelow) return `下方还有 ${activeBelow} 个模型`;
  if (hiddenBelow || totalHidden) return `下方有 ${hiddenBelow || totalHidden} 个已隐藏的模型`;
  return "下方还有模型";
}

